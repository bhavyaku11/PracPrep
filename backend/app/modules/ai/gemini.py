class GeminiAIProvider(BaseAIProvider):
    """Google Gemini Live AI Provider for viva examination practice.

    Leverages Google's Gen AI SDK with schema-constrained JSON output,
    configurable timeouts, and exponential backoff retry for transient network
    and rate-limiting errors.
    """

    def __init__(
        self,
        api_key: Optional[str] = None,
        model_name: Optional[str] = None,
        timeout_seconds: Optional[float] = None,
        max_retries: Optional[int] = None,
        client: Optional[Any] = None,
    ) -> None:
        """Initialize the Gemini provider.

        Args:
            api_key: Optional API key. If omitted, loaded from settings.
            model_name: Model identifier (e.g. 'gemini-2.5-flash').
            timeout_seconds: Timeout per network call in seconds.
            max_retries: Maximum attempts for transient failures.
            client: Optional pre-configured genai.Client instance (useful for mocking).

        Raises:
            AIProviderConfigError: If API key is missing and no client is supplied.
        """
        settings = get_settings()

        if client is not None:
            self._client = client
            self._api_key = api_key or "injected-mock-key"
        else:
            resolved_key = (
                api_key
                or (settings.GEMINI_API_KEY.get_secret_value() if settings.GEMINI_API_KEY else None)
            )
            if not resolved_key or not resolved_key.strip():
                raise AIProviderConfigError(
                    "Google Gemini API key is missing or not configured. Set GEMINI_API_KEY in environment or .env.",
                    provider_id="gemini",
                )
            self._api_key = resolved_key.strip()
            self._client = genai.Client(api_key=self._api_key)

        self._model_name = (
            model_name.strip() if model_name else (settings.GEMINI_MODEL or "gemini-2.5-flash")
        )
        self._timeout_seconds = (
            float(timeout_seconds)
            if timeout_seconds is not None
            else getattr(settings, "GEMINI_TIMEOUT_SECONDS", 10.0)
        )
        self._max_retries = (
            int(max_retries)
            if max_retries is not None
            else getattr(settings, "GEMINI_MAX_RETRIES", 3)
        )

    @property
    def provider_id(self) -> str:
        """Machine identifier for provider registry."""
        return "gemini"

    @property
    def display_name(self) -> str:
        """Human-readable display title for UI."""
        return "Google Gemini"

    @property
    def provider_mode(self) -> VivaProviderModeEnum:
        """Operational category: ai-live."""
        return VivaProviderModeEnum.AI_LIVE

