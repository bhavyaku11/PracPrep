def _sanitize_message(msg: str) -> str:
    """Strip potential API keys, auth headers, and bearer tokens from error text."""
    if not msg:
        return ""
    # Redact Google API key pattern (AIzaSy...)
    sanitized = re.sub(r"AIza[0-9A-Za-z-_]{20,50}", "[REDACTED_API_KEY]", msg)
    # Redact Bearer tokens
    sanitized = re.sub(r"Bearer\s+[A-Za-z0-9\-_\.]+", "Bearer [REDACTED_TOKEN]", sanitized)
    # Redact query params containing key=...
    sanitized = re.sub(r"key=[0-9A-Za-z-_]+", "key=[REDACTED_API_KEY]", sanitized)
    return sanitized


def _clean_json_text(raw_text: str) -> str:
    """Strip markdown code fence blocks if returned by the LLM."""
    cleaned = raw_text.strip()
    if cleaned.startswith("```"):
        lines = cleaned.splitlines()
        if lines and lines[0].startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].strip().startswith("```"):
            lines = lines[:-1]
        cleaned = "\n".join(lines).strip()
    return cleaned


