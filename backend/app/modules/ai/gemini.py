    def _parse_question_generation_response(
        self,
        raw_response: Any,
        request: QuestionGenerationRequest,
    ) -> QuestionGenerationResponse:
        """Parse, validate, and construct QuestionGenerationResponse from raw SDK output."""
        raw_text = getattr(raw_response, "text", None)
        if not raw_text or not raw_text.strip():
            raise AIProviderResponseError(
                "Gemini returned an empty or null response text for question generation.",
                provider_id="gemini",
                raw_response=str(raw_response),
            )

        cleaned_text = _clean_json_text(raw_text)

        try:
            parsed_json = json.loads(cleaned_text)
        except json.JSONDecodeError as err:
            raise AIProviderResponseError(
                f"Gemini response could not be decoded as JSON: {err}",
                provider_id="gemini",
                raw_response=cleaned_text[:500],
                original_error=err,
            ) from err

        try:
            payload = GeminiQuestionGenerationPayload.model_validate(parsed_json)
        except ValidationError as err:
            raise AIProviderResponseError(
                f"Gemini response violated question generation schema: {err}",
                provider_id="gemini",
                raw_response=cleaned_text[:500],
                original_error=err,
            ) from err

        # Filter duplicates deterministically by normalized question_text
        seen_texts: set[str] = set()
        unique_items: list[GeminiGeneratedQuestionItem] = []
        for item in payload.questions:
            normalized = item.question_text.strip().lower()
            if normalized not in seen_texts:
                seen_texts.add(normalized)
                unique_items.append(item)

        if len(unique_items) < request.question_count:
            raise AIProviderResponseError(
                f"Gemini returned {len(unique_items)} unique questions, but {request.question_count} were requested.",
                provider_id="gemini",
                raw_response=cleaned_text[:500],
            )

        final_questions: list[AIGeneratedQuestion] = []
        for idx, item in enumerate(unique_items[: request.question_count], start=1):
            final_questions.append(
                AIGeneratedQuestion(
                    id=str(uuid.uuid4()),
                    question_number=idx,
                    question_text=item.question_text.strip(),
                    topic=item.topic,
                    difficulty=item.difficulty,
                    expected_answer=item.expected_answer.strip() if item.expected_answer else None,
                    key_points=item.key_points,
                    grounded_source_section=item.grounded_source_section,
                )
            )

        return QuestionGenerationResponse(
            questions=final_questions,
            provider_mode=self.provider_mode,
            provider_id=self.provider_id,
            metadata={
                "model": self._model_name,
                "raw_question_count": len(payload.questions),
                "unique_question_count": len(unique_items),
            },
        )

