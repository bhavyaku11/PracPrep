    def _build_question_generation_system_instruction(self) -> str:
        return (
            "You are a rigorous, distinguished academic oral examiner for engineering and science "
            "laboratory practical examinations (viva voce). Your role is to test the student's deep conceptual "
            "understanding, experimental methodology, instrument handling, and analytical rigor.\n\n"
            "STRICT GUIDELINES:\n"
            "1. Ground all questions strictly in the supplied laboratory manual context. Never invent fictional "
            "apparatus, reagents, specifications, or experimental outcomes not supported by the context.\n"
            "2. When the provided context is sparse, formulate questions testing general foundational physics/engineering "
            "principles relevant to the stated subject and title rather than hallucinating specific lab details.\n"
            "3. Every question must be distinct and non-repetitive.\n"
            "4. Provide a clear model expected answer and 2 to 4 essential key points required for full marks.\n"
            "5. Return your response exclusively adhering to the required JSON schema."
        )

    def _build_question_generation_user_prompt(self, request: QuestionGenerationRequest) -> str:
        exp = request.experiment
        prompt_parts = [
            f"Generate exactly {request.question_count} viva examination questions based on the following experiment manual.\n",
            f"EXPERIMENT METADATA:\n- Title: {exp.title}\n- Subject: {exp.subject}",
        ]

        if exp.experiment_number:
            prompt_parts.append(f"- Experiment Number: {exp.experiment_number}")
        if exp.objective:
            prompt_parts.append(f"\nOBJECTIVE:\n{exp.objective}")
        if exp.theory:
            prompt_parts.append(f"\nTHEORY & GOVERNING EQUATIONS:\n{exp.theory}")
        if exp.apparatus:
            prompt_parts.append(f"\nAPPARATUS & INSTRUMENTS:\n{exp.apparatus}")
        if exp.procedure:
            prompt_parts.append(f"\nPROCEDURE & METHODOLOGY:\n{exp.procedure}")
        if exp.observations:
            prompt_parts.append(f"\nOBSERVATIONS:\n{exp.observations}")
        if exp.calculations:
            prompt_parts.append(f"\nCALCULATIONS & ERROR ANALYSIS:\n{exp.calculations}")
        if exp.precautions:
            prompt_parts.append(f"\nPRECAUTIONS & SAFETY:\n{exp.precautions}")

        prompt_parts.append(
            f"\nSESSION REQUIREMENTS:\n"
            f"- Question Count: {request.question_count}\n"
            f"- Difficulty: {request.difficulty.value}\n"
            f"- Topic Focus: {request.topic_focus.value}\n"
        )

        if request.constraints:
            prompt_parts.append(f"- Additional Constraints: {'; '.join(request.constraints)}")

        return "\n".join(prompt_parts)

    def _build_answer_evaluation_system_instruction(self) -> str:
        return (
            "You are an objective, authoritative academic oral examiner evaluating a student's spoken/written "
            "response in an engineering laboratory viva voce examination.\n\n"
            "EVALUATION CRITERIA:\n"
            "1. Score the answer strictly between 0 and 10:\n"
            "   - 8-10 (correct): Comprehensive answer correctly stating fundamental laws, units, and principles.\n"
            "   - 4-7 (partially-correct): Identifies some relevant concepts but misses key terms or has minor misconceptions.\n"
            "   - 0-3 (incorrect): Irrelevant, severely inaccurate, dismissive ('idk', 'asdf'), or superficial.\n"
            "2. Do NOT reward verbosity or long-winded answers that lack technical substance.\n"
            "3. Do NOT invent facts or criteria absent from the question or experiment manual.\n"
            "4. Provide honest, constructive feedback identifying what the student got right and what was missing.\n"
            "5. Explicitly classify which rubric key points were covered vs missed.\n"
            "6. Provide an actionable oral examination improvement tip."
        )

    def _build_answer_evaluation_user_prompt(self, request: AnswerEvaluationRequest) -> str:
        q = request.question
        prompt_parts = [
            "Please evaluate the following student response for an oral viva voce examination question.\n",
            f"QUESTION DETAILS:\n"
            f"- Question Text: {q.question_text}\n"
            f"- Topic: {q.topic.value}\n"
            f"- Difficulty: {q.difficulty.value}\n"
            f"- Expected Model Answer: {q.expected_answer or 'Not provided'}\n"
            f"- Key Rubric Points: {'; '.join(q.key_points) if q.key_points else 'General accuracy'}\n",
        ]

        if request.experiment:
            prompt_parts.append(
                f"EXPERIMENT CONTEXT:\n- Title: {request.experiment.title}\n- Subject: {request.experiment.subject}"
            )
            if request.experiment.theory:
                prompt_parts.append(f"- Theory: {request.experiment.theory[:400]}")

        if request.previous_answers:
            prompt_parts.append("\nPREVIOUS QUESTIONS & ANSWERS IN THIS SESSION:")
            for prev in request.previous_answers[-3:]:
                prompt_parts.append(
                    f"Q{prev.question_number}: {prev.question_text}\n"
                    f"Student Answer: {prev.student_answer}\n"
                    f"Verdict: {prev.verdict.value} (Score: {prev.score}/10)\n"
                )

        prompt_parts.append(
            f"\nSTUDENT'S SUBMITTED RESPONSE TO EVALUATE:\n\"{request.student_answer}\"\n"
        )
        return "\n".join(prompt_parts)

