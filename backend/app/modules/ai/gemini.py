class GeminiGeneratedQuestionItem(BaseModel):
    """Schema for individual question item generated by Gemini."""

    model_config = ConfigDict(extra="forbid")

    question_text: str = Field(min_length=5, max_length=2000)
    topic: VivaTopicEnum
    difficulty: VivaDifficultyEnum
    expected_answer: str = Field(min_length=5, max_length=5000)
    key_points: list[str] = Field(min_length=1)
    grounded_source_section: Optional[str] = Field(default=None, max_length=100)


class GeminiQuestionGenerationPayload(BaseModel):
    """Structured response container for Gemini question generation."""

    model_config = ConfigDict(extra="forbid")

    questions: list[GeminiGeneratedQuestionItem] = Field(min_length=1)


class GeminiAnswerEvaluationPayload(BaseModel):
    """Structured response container for Gemini answer evaluation."""

    model_config = ConfigDict(extra="forbid")

    verdict: EvaluationVerdictEnum
    score: int = Field(ge=0, le=10)
    feedback: str = Field(min_length=1, max_length=2000)
    what_you_got_right: str = Field(default="", max_length=3000)
    what_was_missing: str = Field(default="", max_length=3000)
    expected_answer: str = Field(default="", max_length=5000)
    improvement_tip: str = Field(default="", max_length=2000)
    key_points_covered: list[str] = Field(default_factory=list)
    key_points_missed: list[str] = Field(default_factory=list)


class GeminiParsedSectionsPayload(BaseModel):
    """Structured response container for Gemini laboratory manual section parsing."""

    model_config = ConfigDict(extra="forbid")

    title: Optional[str] = Field(default=None, max_length=255)
    subject: Optional[str] = Field(default=None, max_length=255)
    experiment_number: Optional[str] = Field(default=None, max_length=50)
    objective: Optional[str] = Field(default=None)
    theory: Optional[str] = Field(default=None)
    apparatus: Optional[str] = Field(default=None)
    procedure: Optional[str] = Field(default=None)
    observations: Optional[str] = Field(default=None)
    calculations: Optional[str] = Field(default=None)
    precautions: Optional[str] = Field(default=None)
    result: Optional[str] = Field(default=None)
    additional_notes: Optional[str] = Field(default=None)


