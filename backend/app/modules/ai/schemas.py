    key_points_covered: list[str] = Field(
        default_factory=list,
        description="Rubric key points satisfactorily satisfied by the student",
    )
    key_points_missed: list[str] = Field(
        default_factory=list,
        description="Rubric key points omitted or misunderstood by the student",
    )
    provider_mode: VivaProviderModeEnum = Field(
        description="Provider operational mode: 'demonstration' or 'ai-live'"
    )
    provider_id: str = Field(
        min_length=1,
        max_length=50,
        description="Identifier of evaluating provider (e.g., 'gemini', 'demonstration')",
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Provider-independent operational metadata (e.g. latency, token usage)",
    )
