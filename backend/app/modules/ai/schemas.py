class ParsedExperimentSections(BaseModel):
    """Structured laboratory experiment sections extracted by AI parser."""

    title: Optional[str] = Field(
        default=None,
        max_length=255,
        description="Extracted or inferred experiment title",
    )
    subject: Optional[str] = Field(
        default=None,
        max_length=255,
        description="Academic subject area or laboratory course title",
    )
    experiment_number: Optional[str] = Field(
        default=None,
        max_length=50,
        serialization_alias="experimentNumber",
        description="Optional experiment catalog or sequence code (e.g. 'EXP-01')",
    )
    objective: Optional[str] = Field(
        default=None,
        description="Core experimental aim or objective",
    )
    theory: Optional[str] = Field(
        default=None,
        description="Theoretical background, governing principles, and scientific equations",
    )
    apparatus: Optional[str] = Field(
        default=None,
        description="Required laboratory apparatus, tools, components, and instruments",
    )
    procedure: Optional[str] = Field(
        default=None,
        description="Step-by-step experimental procedure and methodology",
    )
    observations: Optional[str] = Field(
        default=None,
        description="Expected observations, measurement tables, and reading parameters",
    )
    calculations: Optional[str] = Field(
        default=None,
        description="Formulas, calculations, derivations, and error analysis",
    )
    precautions: Optional[str] = Field(
        default=None,
        description="Laboratory safety precautions and handling guidelines",
    )
    result: Optional[str] = Field(
        default=None,
        description="Experimental result, inferences, or conclusion statement",
    )
    additional_notes: Optional[str] = Field(
        default=None,
        serialization_alias="additionalNotes",
        description="Additional relevant sections or notes present in the source text",
    )

    model_config = ConfigDict(extra="forbid", populate_by_name=True)



