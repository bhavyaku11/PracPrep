class AIGeneratedQuestion(BaseModel):
    """Single viva examination question generated by an AI provider."""

    model_config = ConfigDict(extra="forbid")

    id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique question identifier",
    )
    question_number: int = Field(
        ge=1,
        description="1-based sequence index within the session",
    )
    question_text: str = Field(
        min_length=5,
        max_length=2000,
        description="The oral examination question text",
    )
    topic: VivaTopicEnum = Field(description="Question topic category")
    difficulty: VivaDifficultyEnum = Field(
        default=VivaDifficultyEnum.INTERMEDIATE,
        description="Difficulty level of the question",
    )
    expected_answer: Optional[str] = Field(
        default=None,
        max_length=5000,
        description="Authoritative model answer for student review or rubric evaluation",
    )
    key_points: list[str] = Field(
        default_factory=list,
        description="Essential conceptual points required for a full score",
    )
    grounded_source_section: Optional[str] = Field(
        default=None,
        max_length=100,
        description="Lab manual source section (e.g. 'Theory', 'Apparatus', 'Procedure')",
    )


